"""X23: files a machine wrote - skipped, because they name nothing a person wired.

Measured on a 48-checkout machine: 97% of one .NET repo's 442 MB of C# was EF
migrations and ``*.Designer.cs``, and those files were most of the cold read's
time. Generated code repeats what its source already says (a migration repeats
the model, a ``.pb.go`` the ``.proto``), so a link it would show is a link the
source shows too. Two ways to know: the name, before the file is read; and the
marker every common generator writes into the head, after.
"""

from __future__ import annotations

import re

_SUFFIXES = (
    ".designer.cs", ".g.cs", ".g.i.cs", ".generated.cs", ".generated.ts", ".generated.go",
    ".min.js", ".min.mjs", ".bundle.js", ".pb.go", ".pb.gw.go", "_pb2.py", "_pb2_grpc.py",
    "_pb2.pyi", ".pb.ts", "_grpc.pb.go", ".snap",
)  # fmt: skip
_PREFIXES = ("zz_generated",)
# Directories holding generated migrations of an ORM's model, by convention.
_DIRS = frozenset({"migrations"})
_CODE = (".cs", ".py", ".ts", ".js", ".go", ".rb", ".java", ".kt", ".php")
HEAD = 2048
_MARKER = re.compile(
    r"<auto-generated|code generated .{0,80}do not edit|@generated\b|"
    r"this file (?:was|is) (?:automatically |auto-)?generated|autogenerated file",
    re.IGNORECASE,
)


def by_name(path: str) -> bool:
    """A generated file, known by its path alone."""
    low = path.lower()
    parts = low.split("/")
    base = parts[-1]
    if base.endswith(_SUFFIXES) or base.startswith(_PREFIXES):
        return True
    return base.endswith(_CODE) and any(p in _DIRS for p in parts[:-1])


def by_head(text: str) -> bool:
    """A generated file, known by the marker its generator wrote at the top."""
    return bool(_MARKER.search(text[:HEAD]))
